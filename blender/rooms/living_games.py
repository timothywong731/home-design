def _img(name, file, rough, size=None):
    return M.image_mat('living_' + name, os.path.join(ART, file), size_m=size, roughness=rough)


def _since(mb, n0):
    mb.bm.faces.ensure_lookup_table()
    return list(mb.bm.faces)[n0:]


def _uv(faces, mb, fn):
    """Explicit UVs: fn(vertex co) -> (u, v) for every loop of the faces."""
    for f in faces:
        for l in f.loops:
            l[mb.uvl].uv = fn(l.vert.co)


def _quad(mb, pts, mi, uvs):
    mb._f(mb._vs(pts), mi, uvs)


def _walls(mb, outline, z0, z1, mi, uvfn):
    """Vertical quads along a closed 2D outline; the normal is to the right of travel (counter-clockwise outline seen
    from above = outward). uvfn(edge index, s, t) -> (u, v), s along the edge, t up."""
    for k, (a, b) in enumerate(zip(outline, outline[1:] + outline[:1])):
        _quad(mb, [(*a, z0), (*b, z0), (*b, z1), (*a, z1)], mi,
              [uvfn(k, 0, 0), uvfn(k, 1, 0), uvfn(k, 1, 1), uvfn(k, 0, 1)])


