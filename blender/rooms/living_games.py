def _relax(pts, gap=0.0008):
    """Push apart discs set down closer than a diameter + gap (the surveyed centres are +-0.07 cell: two pairs of the
    red back rank overlap by 1-4 mm)."""
    pts = [list(p) for p in pts]
    for _ in range(20):
        moved = False
        for i in range(len(pts)):
            for j in range(i + 1, len(pts)):
                dx, dy = pts[j][0] - pts[i][0], pts[j][1] - pts[i][1]
                d = hypot(dx, dy)
                if d < 2 * PIECE_R + gap:
                    k = (2 * PIECE_R + gap - d) / 2 / d
                    pts[i][0] -= dx * k
                    pts[i][1] -= dy * k
                    pts[j][0] += dx * k
                    pts[j][1] += dy * k
                    moved = True
        if not moved:
            break
    return pts


def _disc(mb, mi, cx, cy, z0, cell, up, n=16):
    """One piece: lathed disc dia 38 x 15 with 2.5 mm round arrises. The flat top carries atlas cell `cell` turned so
    the character's top points along the board-local angle `up` (rad); sides and bottom map to the plain cell."""
    s = 0.25
    uc, vc = (cell % 4 + 0.5) * s, 1 - (cell // 4 + 0.5) * s
    pu, pv = (14 % 4 + 0.5) * s, 1 - (14 // 4 + 0.5) * s
    k = 118 / 1024
    rings = [[mb.bm.verts.new((cx + r * cos(tau * j / n), cy + r * sin(tau * j / n), z0 + z)) for j in range(n)]
             for r, z in PROF]
    for i, (a, b) in enumerate(zip(rings, rings[1:])):
        for j in range(n):
            j2 = (j + 1) % n
            mb._f([a[j], a[j2], b[j2], b[j]], mi, [(pu - 0.1 + 0.2 * j / n, pv - 0.1 + 0.04 * i), (pu - 0.1 + 0.2 * (j + 1) / n, pv - 0.1 + 0.04 * i),
                                                  (pu - 0.1 + 0.2 * (j + 1) / n, pv - 0.06 + 0.04 * i), (pu - 0.1 + 0.2 * j / n, pv - 0.06 + 0.04 * i)])
    mb._f(rings[0][::-1], mi, [(pu + 0.08 * cos(tau * j / n), pv + 0.08 * sin(tau * j / n)) for j in range(n)][::-1])
    mb._f(rings[-1], mi, [(uc + k * cos(tau * j / n - up + pi / 2), vc + k * sin(tau * j / n - up + pi / 2)) for j in range(n)])


def xiangqi(name='living.xiangqi'):
    """Chinese chess set as left on the coffee table in v10: walnut board 0.43 x 0.475 x 0.015 with flush maple lines,
    river and palaces (one generated texture on the top), and the 32 rosewood discs in the opening array, set down
    casually, each with its incised character (red fill on the east army, turquoise on the west, each upright for its
    own player). Board frame: local +x = files from north to south, +y toward red; origin = board centre, bottom."""
    mb = mo.MB()
    board = _img('xiangqi_board', 'games_board.jpg', 0.42)
    n0 = len(mb.bm.faces)
    mb.box((-BW / 2, -BD / 2, 0), (BW / 2, BD / 2, BT), board, bev=0.0015)
    _uv(_since(mb, n0), mb, lambda c: (c.x / BW + 0.5, c.y / BD + 0.5))
    mi = mb.mi(_img('xiangqi_pieces', 'games_pieces.jpg', 0.45))
    rng = random.Random(85)
    xy = _relax([((u - 4) * CELL, (4.5 - v) * CELL) for _, u, v in PIECES])
    for (cell, _, _), (x, y) in zip(PIECES, xy):
        up = (-pi / 2 if cell < 7 else pi / 2) + radians(rng.uniform(-18, 18) if cell < 7 else rng.uniform(-8, 8))
        _disc(mb, mi, x, y, BT, cell, up)
    return mb.finish(name)


# ------------------------------------------------------------------------------------------ inlaid domino box
BX, BY, BH, LH = 0.145, 0.097, 0.030, 0.012      # box 145 x 97, base 30, lid 12 (survey 2.2)
WALL, FLOOR, PAD = 0.007, 0.003, 0.0045
TL, TW, TT = 0.048, 0.024, 0.0075                # domino 48 x 24 x 7.5
ATLAS = {'lid': (0, 0, 870, 582), 'lside': (0, 582, 870, 762), 'sside': (0, 762, 582, 942), 'ledge': (0, 942, 870, 1014),
         'sedge': (0, 942, 582, 1014), 'plain': (880, 600, 1024, 1024)}   # px regions of games_box.jpg (living_games_tex)


def _reg(key, s, t):
    x0, y0, x1, y1 = ATLAS[key]
    return ((x0 + s * (x1 - x0)) / 1024, 1 - (y1 - t * (y1 - y0)) / 1024)


def _domino_k(a, b):
    """Atlas index of tile a-b (a <= b) in a double-six set listed 0-0, 0-1 .. 6-6."""
    return sum(7 - i for i in range(a)) + (b - a)


def _tile(mb, T, Mx, k=None):
    """One domino through matrix Mx (origin = centre of its underside, long axis local x); k = atlas face, None = lying
    face down (the plain back up)."""
    n0 = len(mb.bm.faces)
    mb.at(Mx)
    mb.box((-TL / 2, -TW / 2, 0), (TL / 2, TW / 2, TT), T, bev=0.0012)
    mb.at()
    Mi = Mx.inverted()
    col, row = (k % 4, k // 4) if k is not None else (0, 0)
    for f in _since(mb, n0):
        loc = [Mi @ l.vert.co for l in f.loops]
        top = k is not None and min(c.z for c in loc) > TT - 1e-4
        for l, c in zip(f.loops, loc):
            l[mb.uvl].uv = ((col + c.x / TL + 0.5) / 4, 1 - (row + 1) / 8 + (c.y / TW + 0.5) / 8) if top else \
                (0.5 + c.x * 2, 0.06 + c.y * 2)


def domino_box(name='living.domino_box'):
    """Bone and mother-of-pearl inlaid box 145 x 97 x 42 (base 30, lid 12) of a double-six set, frame: local +x = long
    axis, +y = hinge side, origin = centre of the underside. -> (base with 25 dominoes in four layers, lid hinged on the
    +y top edge, the three top-layer tiles the owner takes out, the same three lying on the table in front of the box).
    The lid top, sides and lid edge carry the generated marquetry atlas; inside crimson velvet."""
    A = _img('domino_box', 'games_box.jpg', 0.28)
    V = M.solid('living_box_velvet', '#A01C24', 0.95)
    _bsdf(V).inputs['Sheen Weight'].default_value = 0.3                  # more washes the crimson out to pink
    T = _img('dominoes', 'games_dominoes.jpg', 0.3)
    hx, hy, ix, iy = BX / 2, BY / 2, BX / 2 - WALL, BY / 2 - WALL
    out = [(-hx, -hy), (hx, -hy), (hx, hy), (-hx, hy)]            # counter-clockwise: normals outward
    inn = [(-ix, -iy), (-ix, iy), (ix, iy), (ix, -iy)]            # clockwise: normals into the cavity
    side = lambda key_l, key_s: (lambda k, s, t: _reg(key_l if k % 2 == 0 else key_s, s, t))
    plain = lambda k, s, t: _reg('plain', 0.2 + 0.6 * s, 0.2 + 0.6 * t)

    def rim(mb, z, mi, down=False):                              # flat ring between the outer and inner outline
        cs = [(-hx, -hy, -ix, -iy), (hx, -hy, ix, -iy), (hx, hy, ix, iy), (-hx, hy, -ix, iy)]
        for a, b in zip(cs, cs[1:] + cs[:1]):
            q = [(a[0], a[1], z), (b[0], b[1], z), (b[2], b[3], z), (a[2], a[3], z)]
            _quad(mb, q[::-1] if down else q, mi, [_reg('plain', 0.3, 0.3)] * 4)

    mb = mo.MB()
    a, v = mb.mi(A), mb.mi(V)
    _walls(mb, out, 0.0, BH, a, side('lside', 'sside'))
    _quad(mb, [(-hx, -hy, 0), (-hx, hy, 0), (hx, hy, 0), (hx, -hy, 0)], a, [_reg('plain', s, t) for s, t in ((0, 0), (0, 1), (1, 1), (1, 0))])
    rim(mb, BH, a)
    _walls(mb, inn, FLOOR, BH, v, plain)
    _quad(mb, [(-ix, -iy, FLOOR), (ix, -iy, FLOOR), (ix, iy, FLOOR), (-ix, iy, FLOOR)], v, [(0, 0)] * 4)
    # dominoes: four layers of seven (five across the short way + two along the long way); the top layer jumbled
    rng = random.Random(28)
    ks = list(range(28))
    taken = [_domino_k(6, 6), _domino_k(2, 3), _domino_k(4, 4)]   # out on the table while the lid is open (g0604)
    for t in taken:
        ks.remove(t)
    rng.shuffle(ks)
    slots = [(-0.049 + 0.0245 * i, -0.0165, 90) for i in range(5)] + [(-0.0245, 0.0225, 0), (0.0245, 0.0225, 0)]
    inner = mo.MB()
    for layer in range(4):
        top = layer == 3
        for i, (x, y, r) in enumerate(slots):
            dx, dy = rng.uniform(-0.0008, 0.0008), (0.0018 * (1 if i % 2 else -1) if top and r else rng.uniform(-0.0008, 0.0008))
            dr = rng.uniform(-6, 6) if top and not r else rng.uniform(-0.8, 0.8)
            Mx = Tr(x + dx, y + dy, FLOOR + TT * layer + 0.0002) @ Rz(r + dr)
            if top and i in (1, 3, 5):
                _tile(inner, T, Mx, taken[(1, 3, 5).index(i)])
            else:
                _tile(mb, T, Mx, None if (top and i == 2) else ks.pop())
    base = mb.finish(name)
    tiles_in = inner.finish(name + '.tiles_in')
    # lid, modelled shut: top, edge, underside rim, velvet pad
    mb = mo.MB()
    a, v = mb.mi(A), mb.mi(V)
    z1 = BH + LH
    _quad(mb, [(-hx, -hy, z1), (hx, -hy, z1), (hx, hy, z1), (-hx, hy, z1)], a,
          [_reg('lid', s, t) for s, t in ((0, 0), (1, 0), (1, 1), (0, 1))])
    _walls(mb, out, BH, z1, a, side('ledge', 'sedge'))
    rim(mb, BH, a, down=True)
    _walls(mb, inn, BH, BH + PAD, v, plain)
    _quad(mb, [(-ix, -iy, BH + PAD), (-ix, iy, BH + PAD), (ix, iy, BH + PAD), (ix, -iy, BH + PAD)], v, [(0, 0)] * 4)
    lid = mb.finish(name + '.lid')
    # the three on the table, face up in front of the open box toward its +x end (survey 2.2: box frame x, distance in
    # front of the front face, turn)
    mb = mo.MB()
    for t, (x, d, r) in zip(taken, ((0.03, 0.085, 0), (0.10, 0.035, 55), (0.17, 0.02, 10))):
        _tile(mb, T, Tr(x, -hy - d, 0.0002) @ Rz(r), t)
    loose = mb.finish(name + '.tiles_out')
    return base, lid, tiles_in, loose


# ------------------------------------------------------------------------------------------ solitaire
SOL_PROF = [(0, 0), (0.1185, 0), (0.120, 0.0015), (0.120, 0.009), (0.1195, 0.0115), (0.1175, 0.0138), (0.114, 0.015),
            (0.110, 0.015), (0.107, 0.014), (0.105, 0.0122), (0.1025, 0.0112), (0.0995, 0.0114), (0.097, 0.0128),
            (0.0955, 0.015), (0.0948, 0.0158), (0.0938, 0.0158), (0.093, 0.015), (0, 0.015)]
MARBLE_R, PITCH = 0.01025, 0.0238


def solitaire(name='living.solitaire', turn=9.0):
    """Turned burr-wood solitaire board dia 0.24 x 15 (flat field dia 0.188 ending in a 1.5 mm bead, a 13 mm gutter
    4 mm deep, a rounded 12 mm lip level with the field), high polish; the English cross of 33 holes at 23.8 mm, every
    one filled with a 20.5 mm onyx marble (cream, honey / tan, banded brown and cream, at random). The lattice is
    turned `turn` degrees. Origin = centre of the underside."""
    mb = mo.MB()
    n0 = len(mb.bm.faces)
    mb.lathe(SOL_PROF, _img('solitaire', 'games_solitaire.jpg', 0.25), 40)     # polished, but no glare wash-out
    _uv(_since(mb, n0), mb, lambda c: (c.x / 0.24 + 0.5, c.y / 0.24 + 0.5))
    mats = [M.solid('living_onyx_cream', '#E6E1D3', 0.15), M.solid('living_onyx_honey', '#CDBF9C', 0.15),
            M.solid('living_onyx_tan', '#A8906A', 0.18), M.solid('living_onyx_pink', '#B39886', 0.18)]
    band = _img('onyx_strata', 'games_onyx.jpg', 0.12)
    k, seg = 6, 12                                    # 30 deg steps: smooth-shaded under finish's 35 deg rule
    prof = [(MARBLE_R * sin(pi * i / k), -MARBLE_R * cos(pi * i / k)) for i in range(k + 1)]
    prof[0], prof[-1] = (0, -MARBLE_R), (0, MARBLE_R)
    rng = random.Random(33)
    c, s = cos(radians(turn)), sin(radians(turn))
    z = 0.015 + MARBLE_R - 0.0035                     # seated in its hole
    for i in range(-3, 4):
        for j in range(-3, 4):
            if abs(i) > 1 and abs(j) > 1:
                continue
            x, y = i * PITCH, j * PITCH
            r = rng.random()
            m = band if r < 0.34 else mats[0] if r < 0.6 else mats[1] if r < 0.78 else mats[2] if r < 0.94 else mats[3]
            Mx = Tr(x * c - y * s, x * s + y * c, z) @ Rz(rng.uniform(0, 360)) @ Rx(rng.uniform(-70, 70))
            n1 = len(mb.bm.faces)
            mb.at(Mx)
            mb.lathe(prof, m, seg)
            if m is band:                             # strata straight through the ball: planar projection
                Mi, o = Mx.inverted(), rng.uniform(0, 0.5)
                _uv(_since(mb, n1), mb, lambda co: ((Mi @ co).x / (2 * MARBLE_R) * 0.5 + o,
                                                     (Mi @ co).z / (2 * MARBLE_R) * 0.5 + o))
    mb.at()
    return mb.finish(name)
